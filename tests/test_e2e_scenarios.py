    def test_06_test1_topic_python_loops_10_mcqs(self):
        """TEST 1: Topic 'Python Loops' -> 10 MCQs."""
        res = self.client.post("/api/auth/login", json={"email": "alice.test@university.edu", "password": "password123"})
        token = res.get_json()["token"]
        headers = {"Authorization": f"Bearer {token}"}

        payload = {
            "topic": "  python loops  ",
            "num_questions": 10,
            "difficulty": "medium",
            "question_types": ["mcq"]
        }
        res = self.client.post("/api/quizzes/generate", json=payload, headers=headers)
        self.assertEqual(res.status_code, 201)
        data = res.get_json()
        self.assertTrue(data.get("success"))
        quiz = data["quiz"]
        self.assertEqual(quiz["topic"], "Python Loops")
