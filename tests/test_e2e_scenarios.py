    def test_09_test5_flashcards_end_to_end(self):
        """TEST 5: Flashcards for 'Python Loops' end-to-end."""
        res = self.client.post("/api/auth/login", json={"email": "alice.test@university.edu", "password": "password123"})
        token_a = res.get_json()["token"]
        headers_a = {"Authorization": f"Bearer {token_a}"}

        fc_payload = {
            "topic": "  python loops  ",
            "num_cards": 10
        }
        res = self.client.post("/api/flashcards/generate", json=fc_payload, headers=headers_a)
        self.assertEqual(res.status_code, 201)
        data = res.get_json()
        self.assertTrue(data.get("success"))

        deck = data["deck"]
        deck_id = deck["id"]
        cards = deck["cards"]
        self.assertEqual(len(cards), 10)
        self.assertEqual(deck["topic"], "Python Loops")

        # GET /api/flashcards
        res_list = self.client.get("/api/flashcards", headers=headers_a)
        self.assertEqual(res_list.status_code, 200)

        # GET /api/flashcards/<id>
        res_get = self.client.get(f"/api/flashcards/{deck_id}", headers=headers_a)
        self.assertEqual(res_get.status_code, 200)

        # PUT /api/flashcards/<deck_id>/cards/<card_id>
        first_card_id = cards[0]["id"]
        res_update = self.client.put(
            f"/api/flashcards/{deck_id}/cards/{first_card_id}",
            json={"mastered": True, "difficulty_rating": "easy"},
            headers=headers_a
        )
        self.assertEqual(res_update.status_code, 200)

        # User B isolation
        res_b = self.client.post("/api/auth/login", json={"email": "bob.test@university.edu", "password": "password456"})
        token_b = res_b.get_json()["token"]
        headers_b = {"Authorization": f"Bearer {token_b}"}

        res_b_list = self.client.get("/api/flashcards", headers=headers_b)
        self.assertEqual(len(res_b_list.get_json()["decks"]), 0)

        # Delete Deck
        res_del = self.client.delete(f"/api/flashcards/{deck_id}", headers=headers_a)
        self.assertEqual(res_del.status_code, 200)

