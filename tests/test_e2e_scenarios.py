            self.assertEqual(q["type"], "mcq")
            self.assertEqual(len(q["options"]), 4)
            self.assertIn(q["correct_answer"], q["options"])
            q_full = f"{q['question']} {q['correct_answer']} {' '.join(q['options'])} {q['explanation']}".lower()

            has_loop_concept = any(k in q_full for k in loop_keywords)
            self.assertTrue(has_loop_concept, f"Question should be about Python loops: {q['question']}")

            for f in forbidden_keywords:
                self.assertNotIn(f, q["question"].lower(), f"Question should not contain unrelated concept '{f}': {q['question']}")

